const pptxgen = require("pptxgenjs");

const pres = new pptxgen();
pres.layout = "LAYOUT_WIDE"; // 13.333 x 7.5
pres.author = "Игорь Иванов, DoctorTeam";
pres.title = "Как выигрывать тендеры";

// ---------- палитра ----------
const BG      = "12141A"; // почти чёрный сине-серый
const CARD    = "1C202B";
const CARD2   = "232838";
const FG      = "F2F4F8";
const MUTED   = "97A0B5";
const GOS     = "4A90D9"; // госы — синий
const CORP    = "9B6BD9"; // госкорпорации — фиолетовый
const COM     = "F0862E"; // коммерция — оранжевый
const MONEY   = "E5484D"; // деньги — красный
const GOOD    = "3DAE72"; // зелёный
const H = "Arial";        // заголовки
const B = "Calibri";      // текст

// ---------- helpers ----------
function S(markerLabel, markerColor, notes) {
  const s = pres.addSlide();
  s.background = { color: BG };
  if (markerLabel) {
    s.addText(markerLabel, {
      x: 8.2, y: 0.3, w: 4.35, h: 0.3, align: "right", margin: 0,
      fontSize: 11, bold: true, color: markerColor, fontFace: B, charSpacing: 2,
    });
    s.addShape(pres.ShapeType.ellipse, {
      x: 12.68, y: 0.36, w: 0.17, h: 0.17, fill: { color: markerColor },
    });
  }
  if (notes) s.addNotes(notes);
  return s;
}

function title(s, text, y) {
  s.addText(text, {
    x: 0.75, y: y === undefined ? 0.85 : y, w: 11.9, h: 1.0, margin: 0,
    fontSize: 36, bold: true, color: FG, fontFace: H, valign: "top",
  });
}

function kicker(s, text, color) {
  s.addText(text, {
    x: 0.75, y: 0.5, w: 7.0, h: 0.35, margin: 0,
    fontSize: 13, bold: true, color: color, fontFace: B, charSpacing: 2,
  });
}

// крупная фраза во весь слайд
function statement(s, text, color, size) {
  s.addText(text, {
    x: 0.9, y: 2.0, w: 11.5, h: 3.4, margin: 0,
    fontSize: size || 46, bold: true, color: color || FG, fontFace: H,
    valign: "middle", lineSpacing: (size || 46) * 1.18,
  });
}

// карточка-подложка
function card(s, x, y, w, h, fill) {
  s.addShape(pres.ShapeType.roundRect, {
    x, y, w, h, rectRadius: 0.08, fill: { color: fill || CARD }, line: { color: fill || CARD, width: 0 },
  });
}

// список с точками-кружками
function dotList(s, items, x, y, w, color, size, pitch) {
  const fs = size || 17;
  const p = pitch || 0.52;
  items.forEach((t, i) => {
    s.addShape(pres.ShapeType.ellipse, {
      x: x, y: y + i * p + fs / 200, w: 0.11, h: 0.11, fill: { color: color },
    });
    s.addText(t, {
      x: x + 0.3, y: y + i * p - 0.06, w: w, h: p, margin: 0,
      fontSize: fs, color: FG, fontFace: B, valign: "top",
    });
  });
}

// стоп-факторы: × + текст
function stopList(s, items, x, y, w) {
  items.forEach((t, i) => {
    s.addText("×", {
      x: x, y: y + i * 0.72, w: 0.4, h: 0.5, margin: 0,
      fontSize: 26, bold: true, color: MONEY, fontFace: H,
    });
    s.addText(t, {
      x: x + 0.45, y: y + i * 0.72 + 0.05, w: w, h: 0.55, margin: 0,
      fontSize: 18, color: FG, fontFace: B, valign: "top",
    });
  });
}

// таблица скоринга с полосками весов
function scoring(s, rows, color, highlightIdx) {
  const x0 = 0.9, y0 = 1.95, pitch = 0.66, barX = 6.6, barMax = 4.0;
  rows.forEach((r, i) => {
    const hl = i === highlightIdx;
    if (hl) card(s, x0 - 0.2, y0 + i * pitch - 0.08, 11.6, 0.58, CARD2);
    s.addText(r[0], {
      x: x0, y: y0 + i * pitch, w: 5.5, h: 0.45, margin: 0,
      fontSize: 16, bold: hl, color: hl ? FG : FG, fontFace: B, valign: "middle",
    });
    s.addShape(pres.ShapeType.roundRect, {
      x: barX, y: y0 + i * pitch + 0.13, w: barMax, h: 0.19, rectRadius: 0.05,
      fill: { color: CARD2 }, line: { color: CARD2, width: 0 },
    });
    s.addShape(pres.ShapeType.roundRect, {
      x: barX, y: y0 + i * pitch + 0.13, w: (r[1] / 25) * barMax, h: 0.19, rectRadius: 0.05,
      fill: { color: color }, line: { color: color, width: 0 },
    });
    s.addText(String(r[1]), {
      x: 10.9, y: y0 + i * pitch, w: 1.0, h: 0.45, margin: 0, align: "right",
      fontSize: 20, bold: true, color: color, fontFace: H, valign: "middle",
    });
  });
}

// сетка из 168 точек, highlight — сколько выделить
function dotGrid(s, x, y, highlight, color) {
  const cols = 14, rows = 12, pitch = 0.215, d = 0.115;
  for (let i = 0; i < 168; i++) {
    const c = i % cols, r = Math.floor(i / cols);
    const on = i < highlight;
    s.addShape(pres.ShapeType.ellipse, {
      x: x + c * pitch, y: y + r * pitch, w: d, h: d,
      fill: { color: on ? color : "2E3444" },
    });
  }
}

